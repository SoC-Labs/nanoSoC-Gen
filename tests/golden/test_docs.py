class TestFmtSize:
    pytestmark = pytest.mark.unit

    @pytest.mark.parametrize(
        "size, expected",
        [
            (0x40000000, "1 GB"),     # exactly 1 GiB  -> GB branch (L31-32)
            (0x60000000, "1.5 GB"),   # fractional GiB -> one decimal
            (0x100000, "1 MB"),       # exactly 1 MiB
            (0x180000, "1.5 MB"),     # fractional MiB
            (0x800, "2 KB"),          # exactly 2 KiB
            (0x600, "1.5 KB"),        # fractional KiB
            (0x10, "16 B"),           # below 1 KiB -> bytes (L39)
            (0, "0 B"),               # zero -> bytes
        ],
    )
    def test_buckets(self, size, expected):
        assert _fmt_size(size) == expected

    def test_kb_boundary_is_bytes_below_1024(self):
        assert _fmt_size(1023) == "1023 B"
        assert _fmt_size(1024) == "1 KB"


