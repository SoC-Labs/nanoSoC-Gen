class TestContextStructure:
    pytestmark = pytest.mark.unit

    def test_big_param_default_rendered_hex(self, fixtures_dir, tmp_path):
        """DOC-04: an int param default >= 256 is rendered as 0x%X in the
        parameter table (L96-97). minimal_soc's SYS_CLK_FREQ_HZ = 50_000_000."""
        top = build_module_from_yaml(fixtures_dir, "minimal_soc.yaml")
        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        # 50_000_000 == 0x2FAF080 — big default folded to hex, small ones plain.
        assert "`SYS_CLK_FREQ_HZ` | int | 0x2FAF080 |" in text
        assert "`SYS_ADDR_W` | int | 32 |" in text

    def test_clocks_resets_interfaces_tables(self, fixtures_dir, tmp_path):
        """DOC-05: the clock / reset / interface builders populate their tables
        from the model (L106-132)."""
        top = build_module_from_yaml(fixtures_dir, "minimal_soc.yaml")
        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        assert "## Clock Domains" in text
        assert "`sys_hclk` | external | AHB clock |" in text
        assert "## Reset Domains" in text
        assert "`sys_hresetn` | low | external | AHB reset |" in text
        assert "## External Interfaces" in text
        # interface width comes from params.WIDTH (1) for the wire ports.
        assert "`sys_hclk` | wire | in | 1 |" in text

    def test_instance_block_params_ifaces_and_addr_region(self, fixtures_dir,
                                                          tmp_path):
        """DOC-06: per-instance block carries desc, param overrides, interfaces
        from the resolved module, and the address region the interconnect target
        gives it (L134-194). u_sram_0 is addressable at 0x00000000+4KB."""
        top = build_module_from_yaml(fixtures_dir, "minimal_soc.yaml")
        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        assert "### u_sram_0 : tiny_region" in text
        # desc pulled from resolved module
        assert "Minimal general-purpose SRAM region" in text
        # param override row + interface row from the resolved module
        assert "`RAM_ADDR_W` | `$SRAM_RAM_ADDR_W` |" in text
        assert "`ahb_slave` | ahb | target |" in text
        # address-map row derived from the interconnect target
        assert "| sram_0 | 0x00000000 | 0x00000FFF | 4 KB | rwx |" in text

    def test_memory_map_sorted_and_sub_region_from_address_decode(
            self, fixtures_dir, tmp_path):
        """DOC-07: the memory map is base-sorted, and an interconnect target
        backed by an addressable child carrying an address_decode emits the
        indented sub-region rows (L196-219 + the address_decode branch of
        _collect_sub_regions, L239-252). apb_bridge_soc has the regs slot."""
        top = build_module_from_yaml(fixtures_dir, "apb_bridge_soc.yaml")
        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        # base ordering: sram_0 (0x0) precedes apb_periph_0 (0x40000000).
        sram_idx = text.index("| sram_0 | u_sram_0 |")
        apb_idx = text.index("| apb_periph_0 | u_apb_periph_0 |")
        assert sram_idx < apb_idx
        # indented sub-region row absolute-addressed at the slot base.
        assert "|   regs_0 | tiny_apb_periph | 0x40000000 | 0x40000FFF |" in text

    def test_interconnect_connectivity_and_hierarchy(self, fixtures_dir,
                                                     tmp_path):
        """DOC-08: interconnect connectivity lists each initiator's visible
        targets (L254-270) and the ASCII hierarchy tree renders the top + the
        addressable child with its tag (L272-297)."""
        top = build_module_from_yaml(fixtures_dir, "two_region_soc.yaml")
        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        assert "### two_region_ahb_interconnect (ahb_lite)" in text
        # the single initiator sees both targets.
        assert "| cpu_m |  | sram_0, sram_1 |" in text
        assert "two_region_soc (top)" in text
        assert "└── u_sram_1 : tiny_region [addressable]" in text
        assert "├── u_sram_0 : tiny_region [addressable]" in text


