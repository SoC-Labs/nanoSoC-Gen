"""Golden + unit tests for ``soc_model/backends/docs.py`` and the
``soc_model/visualizer`` re-export shim.

The docs backend (:class:`SoCDocsBackend`) renders a single Markdown design
document via jinja2. Unlike ``text.py`` its output is NON-deterministic: the
template injects ``datetime.datetime.now()`` into a
``> Auto-generated by nanosoc_gen on <YYYY-MM-DD HH:MM:SS>.`` line. That exact
line is matched by the generator's own ``soc_model.utils._TIMESTAMP_LINE_RE``
(``> Auto-generated.*on \\d{4}-\\d{2}-\\d{2} \\d{2}:\\d{2}:\\d{2}.*``), so the
shared :func:`assert_matches_snapshot` — which strips timestamps from BOTH
sides before comparing — yields a byte-stable golden without ever pinning the
clock.

Tier split:
  * ``golden`` — date-stripped snapshots of the rendered design doc for the
    hermetic fixtures, with structural teeth so a vacuous golden cannot pass.
  * ``unit``   — ``_fmt_size`` buckets, the no-jinja2 guard (via monkeypatch),
    and structural assertions on small in-memory / fixture-built ``Module``
    objects, including the two branches no committed fixture reaches
    (inline-interface instances, nested-interconnect sub-regions).

Scope note: this file owns ONLY ``docs.py`` and the two-line
``visualizer.py`` re-export shim. The 110 KB ``html.py`` backend that the
shim points at is smoke-tested elsewhere (``tests/unit/test_backends_misc.py``)
and is out of remit here.
"""

