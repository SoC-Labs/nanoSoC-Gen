@pytest.mark.golden
@pytest.mark.parametrize("fixture", ["minimal_soc", "two_region_soc",
                                     "apb_bridge_soc"])
def test_design_doc_golden(fixture, fixtures_dir, tmp_path, request):
    top = build_module_from_yaml(fixtures_dir, f"{fixture}.yaml")
    out = SoCDocsBackend(top).generate(tmp_path)
    text = out.read_text()

    # Structural teeth so an empty/error golden cannot silently pass.
    assert f"# {top.name} Design Documentation" in text
    assert "> Auto-generated by nanosoc_gen on " in text
    assert "## Design Parameters" in text
    assert "## Memory Map" in text
    assert "## Hierarchy Tree" in text
    assert f"{top.name} (top)" in text
    # The non-deterministic date line really is the only thing _strip_timestamps
    # removes here — proves the golden compare is date-insensitive.
    stripped = _strip_timestamps(text)
    assert "Auto-generated by nanosoc_gen on " not in stripped

    assert_matches_snapshot(
        text, SNAPSHOTS / fixture / f"{fixture}_design_doc.md", request)


