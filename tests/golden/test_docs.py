class TestGenerateContract:
    pytestmark = pytest.mark.unit

    def test_generate_writes_named_non_empty_md(self, fixtures_dir, tmp_path):
        """DOC-02: generate() returns ``<output_dir>/<name>_design_doc.md`` and
        writes non-empty Markdown into a (created) output dir."""
        top = build_module_from_yaml(fixtures_dir, "minimal_soc.yaml")
        out_dir = tmp_path / "made" / "by" / "generate"   # does not exist yet
        out = SoCDocsBackend(top).generate(out_dir)

        assert out is not None
        assert out == out_dir / "minimal_soc_design_doc.md"
        assert out.exists()
        assert out.read_text().strip(), "docs backend wrote empty output"
        # the parents=True mkdir created the nested output dir.
        assert out_dir.is_dir()

    def test_generate_accepts_str_output_dir(self, fixtures_dir, tmp_path):
        """generate() coerces a str output_dir via Path() (L54)."""
        top = build_module_from_yaml(fixtures_dir, "minimal_soc.yaml")
        out = SoCDocsBackend(top).generate(str(tmp_path))
        assert out is not None and out.exists()

    def test_no_jinja2_guard_returns_none(self, fixtures_dir, tmp_path,
                                          monkeypatch, capsys):
        """DOC-03: when jinja2 is unavailable (Environment is None) generate()
        warns and returns None without writing anything (L50-52). jinja2 IS
        installed here, so monkeypatch the symbol to exercise the guard."""
        import soc_model.backends.docs as docs_mod
        monkeypatch.setattr(docs_mod, "Environment", None)
        top = build_module_from_yaml(fixtures_dir, "minimal_soc.yaml")
        assert docs_mod.SoCDocsBackend(top).generate(tmp_path) is None
        assert "jinja2 not available" in capsys.readouterr().out
        assert not (tmp_path / "minimal_soc_design_doc.md").exists()


