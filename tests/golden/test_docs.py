class TestEdgeBranches:
    pytestmark = pytest.mark.unit

    def test_inline_interfaces_when_no_resolved_module(self, tmp_path):
        """DOC-09: an instance with NO resolved_module but inline_interfaces uses
        those for the interface table (the elif branch, L170-172). No committed
        fixture hits this — an RTL-style instance with inline interfaces does."""
        inst = Instance(instance_name="u_rtl_0", module_name="custom_rtl",
                        is_rtl_module=True)
        inst.resolved_module = None
        inst.inline_interfaces = [
            Interface(name="ahb_s", type="ahb", direction="target",
                      params={"ADDR_WIDTH": 32}, desc="inline AHB slave"),
            Interface(name="irq", type="wire", direction="out",
                      params={"WIDTH": 1}, desc="interrupt out"),
        ]
        top = Module(name="inline_soc", gen=True, desc="inline-iface SoC")
        top.instances = [inst]

        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        assert "### u_rtl_0 : custom_rtl" in text
        # *Standalone RTL module* note from the is_rtl_module branch.
        assert "Standalone RTL module" in text
        # interfaces sourced from inline_interfaces (no resolved module).
        assert "**Interfaces:**" in text
        assert "`ahb_s` | ahb | target | inline AHB slave |" in text
        assert "`irq` | wire | out | interrupt out |" in text

    def test_nested_interconnect_sub_regions(self, tmp_path):
        """DOC-10: a target backed by a child whose resolved module has its OWN
        interconnect emits absolute-addressed nested sub-region rows (the
        child-interconnect branch of _collect_sub_regions, L224-237). No
        committed fixture's subsystem target carries an instance, so build one."""
        # Child subsystem with its own internal interconnect + two windows.
        child = Module(name="sub_ss", gen=True, desc="subsystem")
        child_ic = Interconnect(name="sub_ss_ic", type="ahb_lite")
        child_ic.targets = [
            # out of order so the sort (key=base) is exercised too.
            InterconnectTarget(name="ctrl", base=0x2000, size=0x1000,
                               sw_access="rw", region_type="periph"),
            InterconnectTarget(name="ram", base=0x0000, size=0x800,
                               sw_access="rwx", region_type="memory"),
        ]
        child.interconnects = [child_ic]

        # Parent target that maps the child instance at 0x50000000.
        sub_inst = Instance(instance_name="u_sub_0", module_name="sub_ss",
                            addressable=True, resolved_module=child)
        top = Module(name="nested_soc", gen=True, desc="nested SoC")
        top.instances = [sub_inst]
        top_ic = Interconnect(name="nested_ic", type="ahb_lite")
        top_ic.targets = [
            InterconnectTarget(name="sub_0", instance="u_sub_0",
                               base=0x50000000, size=0x10000,
                               sw_access="rw", region_type="subsystem"),
        ]
        top_ic.initiators = [
            InterconnectInitiator(
                name="cpu_m",
                targets=[InterconnectInitiatorTarget("sub_0")],
            )
        ]
        top.interconnects = [top_ic]

        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        # parent subsystem window.
        assert "| sub_0 | u_sub_0 | 0x50000000 | 0x5000FFFF |" in text
        # nested sub-regions absolute-addressed at parent_base + child base,
        # base-sorted: ram (0x50000000) before ctrl (0x50002000).
        ram_idx = text.index("|   ram | ")
        ctrl_idx = text.index("|   ctrl | ")
        assert ram_idx < ctrl_idx
        assert "|   ram |  | 0x50000000 | 0x500007FF |" in text
        assert "|   ctrl |  | 0x50002000 | 0x50002FFF |" in text

    def test_hierarchy_recurses_into_child_with_instances(self, tmp_path):
        """DOC-11: the hierarchy tree recurses into a resolved child that has its
        OWN instances, rendering the grandchild one level deeper with the
        indentation prefix (L293-296). No committed fixture's top instance has a
        resolved module bearing further instances, so build one."""
        grandchild_parent = Module(name="child_ss", gen=True)
        grandchild_parent.instances = [
            Instance(instance_name="u_grandchild", module_name="leaf"),
        ]
        inst = Instance(instance_name="u_parent", module_name="child_ss",
                        addressable=True, resolved_module=grandchild_parent)
        top = Module(name="tree_soc", gen=True, desc="deep tree")
        top.instances = [inst]

        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        assert "tree_soc (top)" in text
        assert "└── u_parent : child_ss [addressable]" in text
        # the grandchild is rendered one level deeper, indented past the
        # parent's connector column.
        gc_line = next(ln for ln in text.splitlines() if "u_grandchild" in ln)
        assert "└── u_grandchild : leaf" in gc_line
        assert gc_line.startswith("    "), "grandchild must be indented one level"

    def test_empty_module_renders_skeleton(self, tmp_path):
        """A bare Module (no params/clocks/resets/instances/interconnects) still
        renders the title + Overview + (empty) Memory Map without crashing.
        Exercises the {% if %} guards in the template against empty lists."""
        top = Module(name="bare_soc", gen=True, desc="nothing here")
        text = SoCDocsBackend(top).generate(tmp_path).read_text()
        assert "# bare_soc Design Documentation" in text
        assert "nothing here" in text
        assert "## Memory Map" in text
        # no clock/reset domains -> those optional sections are omitted.
        assert "## Clock Domains" not in text
        assert "## Reset Domains" not in text
        # hierarchy tree still prints the lone top node.
        assert "bare_soc (top)" in text


